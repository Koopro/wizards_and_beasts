#!/usr/bin/env python3
"""Real 3D models for the items that are held, not just listed.

`item_icons.py` and `canon_sprites.py` gave every item a proper sprite, but a sprite is
still a flat card: Minecraft extrudes `item/generated` into a wafer, so a goblet in your
hand is a goblet-shaped biscuit. For the props a player actually holds — potions, books,
wands' cores, a Snitch, the Sword of Gryffindor — a few cuboids read enormously better in
first person, on the ground and in an item frame.

Each item is authored once as a list of boxes. Both outputs come from that one list:

  - `models/item/<id>.json`  the cuboid model, with per-face UVs pointing into
  - `textures/item/<id>_3d.png`  a box-UV atlas painted to match

Deriving both from the same source is the point. A hand-authored model and a
hand-authored texture drift the moment either is edited; here a box cannot be moved
without its UVs moving with it.

The flat sprite stays on disk and is still what the inventory shows for items this tool
does not cover, so nothing regresses if an item is dropped from the list. Base colours are
lifted from the sprite catalogues in `item_icons.py` and `canon_sprites.py` so the model
and the icon are recognisably the same object.

Two things a box carries besides its extents:

  - a *material*, which decides how its faces are painted. Sixteen surface treatments,
    because "brass" and "bone" and "velvet" are not the same object in a different hue,
    and a cuboid with nothing but a flat fill and a light direction reads as a brick.
  - an optional *rotation*, so a Snitch's wing or a quill's shaft can lean. Minecraft
    allows one axis per element at ±22.5 or ±45 degrees, and nothing else.

Run from the repo root:  python tools/item_models_3d.py [--force] [--only id,id]
                         python tools/item_models_3d.py --list
"""

import argparse
import json
import math
import os
import re
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from artgen_common import hx, is_regenerable, marker, mix, posterise, save  # noqa: E402
import item_display  # noqa: E402

ASSETS = "src/main/resources/assets/wizards_and_beasts"
ITEM_TEX_DIR = os.path.join(ASSETS, "textures", "item")
ITEM_MODEL_DIR = os.path.join(ASSETS, "models", "item")
GENERATED_MODEL_DIR = "src/generated/resources/assets/wizards_and_beasts/models/item"
MODEL_PROVIDER = "src/main/java/at/koopro/wizardsandbeasts/datagen/ModModelProvider.java"
CANON_REGISTRY = "src/main/java/at/koopro/wizardsandbeasts/registry/CanonItemRegistry.java"

MARKER = marker("item_models_3d.py")
CREDIT = "generated by tools/item_models_3d.py"

# Texels per model unit. At 1 a bottle's belly got six texels across and every material
# treatment below — a brushed band, a page edge, a facet — landed on the same two or three
# pixels and turned to mush. 2 is the first density where they read as what they are, and
# still leaves a 12-unit-wide book cover at 24 texels, comfortably inside a 128px sheet.
DETAIL = 2

# Grown to fit rather than fixed: a four-box vial packs into 32px and a seven-box Pensieve
# needs 128. Face UVs in a model are always on a 0..16 scale regardless of resolution,
# hence a UV scale derived from whichever size the item ended up needing.
ATLAS_SIZES = (32, 64, 128, 256)

# How each prop is held is not written here: `item_display.py` derives every display transform
# from the model's own bounds and the hold class its builder is tagged with (see HOLD_BY_BUILDER).

# Directional light baked into the texture, matching the beast skins: top lit, underside
# dark, front brighter than back. Item models get no dynamic shading in the GUI, so
# without this a cuboid reads as a flat silhouette.
FACE_SHADE = {"up": 1.22, "down": 0.68, "north": 1.04, "south": 0.90, "east": 0.84, "west": 0.98}
HILIGHT = (255, 246, 224)
SHADOW = (16, 14, 24)

# Base grey for a tinted box. Minecraft tinting is *multiplicative*, so whatever is painted
# here is multiplied by the runtime colour: paint it in colour and you get that colour times
# the brew's, which is nobody's idea of Felix Felicis. Near-white keeps the result faithful to
# the tint while leaving enough headroom below 255 for the shading and specular band to survive.
TINT_BASE = "#e2e2e2"


def lit(rgb, f):
    if f >= 1.0:
        return mix(rgb + (255,), HILIGHT + (255,), min(0.55, (f - 1.0) * 0.95))[:3]
    return mix(rgb + (255,), SHADOW + (255,), min(0.60, (1.0 - f) * 0.95))[:3]


def noise(seed, x, y):
    n = (x * 374761393 + y * 668265263 + seed * 1274126177) & 0xFFFFFFFF
    n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((n ^ (n >> 16)) & 0xFFFF) / 65535.0


# --------------------------------------------------------------------------- materials
#
# A material is a function of the position within one face. It returns a light multiplier
# and, optionally, a colour to blend over the result — a crack, a glint, a line of type.
# Everything about how a surface looks lives here rather than in the catalogue, so a box
# only has to say what it is made of.
#
#   (i, j)   texel within the face, origin top-left
#   (fw, fh) face size in texels
#   face     which of the six, for treatments that only make sense on a side or a top
#   seed     stable per-box, so a grain pattern does not shift between runs
#   rnd      noise(seed, i, j), precomputed because most materials want it

def m_solid(i, j, fw, fh, face, seed, rnd):
    return 1.0, None


def m_glass(i, j, fw, fh, face, seed, rnd):
    """A bright vertical band down one side, which is what sells a cuboid as a bottle."""
    if face in ("up", "down"):
        return 1.08, None
    f = 1.0
    if fw >= 4 and i == max(1, fw // 6):
        f = 1.42
    elif fw >= 6 and i == fw - 2:
        f = 0.80
    return f, None


def m_liquid(i, j, fw, fh, face, seed, rnd):
    """Darkens with depth and catches the light at the meniscus."""
    if face == "up":
        return 1.20, None
    if face == "down":
        return 0.72, None
    f = 1.10 - 0.36 * (j / max(1, fh - 1))
    if j == 0:
        f = 1.40
    if fw >= 4 and i == max(1, fw // 6):
        f *= 1.12
    return f, None


def m_paper(i, j, fw, fh, face, seed, rnd):
    """Ruled leaves on the flat, cut page edges on the sides of a page block."""
    if face in ("east", "west") and fw >= 3:
        return (1.06 if i % 2 == 0 else 0.90), None
    return (1.03 if j % 2 == 0 else 0.96), None


def m_print(i, j, fw, fh, face, seed, rnd):
    """A masthead over ragged-right lines of type, in two columns with a gutter.

    Every other row set full width is not text, it is a venetian blind. Lines every third
    row, each ending where its own noise says, is the least that reads as print.
    """
    if face in ("north", "south") and fw >= 10 and fh >= 10:
        if 2 <= j <= 3 and 2 < i < fw - 2:
            return 1.0, ((40, 36, 34), 0.74)
        gutter = fw // 2
        if j >= 6 and (j - 6) % 3 == 0 and 2 < i < fw - 2 and abs(i - gutter) > 1:
            column = 0 if i < gutter else 1
            start = 3 if column == 0 else gutter + 2
            end = gutter - 2 if column == 0 else fw - 3
            run = start + 2 + noise(seed + 3, column, j) * (end - start - 2)
            if start <= i <= run:
                return 1.0, ((78, 74, 68), 0.46)
    return 1.02, None


def m_leather(i, j, fw, fh, face, seed, rnd):
    """Grain, plus a blind-tooled rule inset from the edge on any face big enough."""
    f = 0.94 + 0.13 * rnd
    if fw >= 8 and fh >= 8 and 2 <= i <= fw - 3 and 2 <= j <= fh - 3 \
            and (i in (2, fw - 3) or j in (2, fh - 3)):
        f *= 0.84
    return f, None


def m_metal(i, j, fw, fh, face, seed, rnd):
    """Lit from above with one brushed sheen band a third of the way down."""
    f = 0.86 + 0.34 * (1.0 - j / max(1, fh - 1))
    if fh >= 6 and j == fh // 3:
        f *= 1.22
    return f * (0.98 + 0.04 * rnd), None


def m_gold(i, j, fw, fh, face, seed, rnd):
    f, _ = m_metal(i, j, fw, fh, face, seed, rnd)
    return f * 1.05, (((255, 250, 214), 0.60) if rnd > 0.965 else None)


def m_gem(i, j, fw, fh, face, seed, rnd):
    """Four facets meeting at the centre, and a glint on the lit corner.

    Only on a face with room for them: split four ways, a face six texels across gives each
    facet three texels, and four competing three-texel wedges read as dither rather than as a
    cut. Small faces take one flat tone and let the silhouette do the work.
    """
    if fw < 8 or fh < 8:
        return 1.06, (((255, 255, 255), 0.35) if i <= 1 and j <= 1 else None)
    u = i / (fw - 1) - 0.5
    v = j / (fh - 1) - 0.5
    f = (0.84, 0.94, 1.06, 1.20)[(1 if u + v > 0 else 0) + (2 if u - v < 0 else 0)]
    if i <= 1 and j <= 1:
        f = 1.34
    return f, None


def m_wood(i, j, fw, fh, face, seed, rnd):
    """Grain runs along the face's long axis, which is the way the plank was cut."""
    g = noise(seed + 11, (i if fh >= fw else j), 0)
    f = 0.90 + 0.18 * g
    if g > 0.88:
        f *= 0.78
    return f * (0.97 + 0.06 * rnd), None


def m_cloth(i, j, fw, fh, face, seed, rnd):
    """A soft weave and the occasional fold.

    Alternating every texel at full strength turned a cloak into wire mesh, so the weave is
    barely there and the folds — sparser, and running only down the face — carry the surface.
    """
    f = 1.02 if (i + j) % 2 == 0 else 0.98
    if fw >= 8 and i % max(4, fw // 3) == 0:
        f *= 0.91
    return f * (0.98 + 0.04 * rnd), None


def m_fur(i, j, fw, fh, face, seed, rnd):
    return 0.80 + 0.42 * noise(seed + 5, i, j // 2), None


def m_bone(i, j, fw, fh, face, seed, rnd):
    """Pale and lit from the tip, cracked here and there, yellowing at the root."""
    f = 1.0 + 0.14 * (1.0 - j / max(1, fh - 1))
    if rnd > 0.945:
        return f, ((150, 140, 112), 0.45)
    if j > fh * 0.68 and rnd > 0.72:
        return f, ((196, 176, 122), 0.32)
    return f, None


def m_stone(i, j, fw, fh, face, seed, rnd):
    f = 0.88 + 0.26 * noise(seed + 2, i // 2, j // 2)
    return (f * 0.82 if rnd > 0.92 else f), None


def m_candy(i, j, fw, fh, face, seed, rnd):
    """One round specular blob up and to the left: the whole of what makes a thing glossy."""
    r = max(1.0, min(fw, fh) * 0.24)
    d = math.hypot(i - fw * 0.30, j - fh * 0.28)
    if d <= r:
        return 1.0, ((255, 255, 255), 0.58 * (1.0 - d / (r + 1.0)))
    return 1.0 + 0.12 * (1.0 - j / max(1, fh - 1)), None


def m_dark(i, j, fw, fh, face, seed, rnd):
    """Velvet: almost no shading, and the occasional cold spark in it."""
    f = 0.92 + 0.10 * rnd
    return f, (((150, 130, 200), 0.32) if rnd > 0.975 else None)


def m_glow(i, j, fw, fh, face, seed, rnd):
    """Not actually emissive — item models get no light — but lit flat and bright enough
    that it reads as the thing giving off light rather than the thing catching it."""
    return 1.22 + 0.22 * noise(seed + 9, i, j), None


def m_feather(i, j, fw, fh, face, seed, rnd):
    """A dark rachis down the middle with barbs combing off it."""
    if fw <= 2 or fh <= 2:
        return 1.0, None
    if i == fw // 2:
        return 0.70, None
    return (1.14 if (i + j) % 3 == 0 else 0.95), None


MATERIALS = {
    "solid": m_solid, "glass": m_glass, "liquid": m_liquid, "paper": m_paper,
    "print": m_print, "leather": m_leather, "metal": m_metal, "gold": m_gold,
    "gem": m_gem, "wood": m_wood, "cloth": m_cloth, "fur": m_fur, "bone": m_bone,
    "stone": m_stone, "candy": m_candy, "dark": m_dark, "glow": m_glow,
    "feather": m_feather,
}


# --------------------------------------------------------------------------- geometry

ROTATION_ANGLES = (-45.0, -22.5, 0.0, 22.5, 45.0)


class Box:
    """One cuboid: model-space extents in 0..16, a colour, a material, and a rotation.

    `tint=True` hands the box's colour over to the game: it is painted greyscale and its faces
    carry `tintindex: 0`, so an ItemTintSource decides what colour it actually is at render
    time. That is what lets one bottle model serve every brew in the catalogue, including ones
    a datapack adds after the model was generated.
    """

    def __init__(self, frm, to, colour, material="solid", tint=False, rot=None, ao=1.0, cover=None):
        if material not in MATERIALS:
            raise SystemExit(f"unknown material {material!r}")
        self.frm = [float(v) for v in frm]
        self.to = [float(v) for v in to]
        self.colour = hx(TINT_BASE if tint else colour)[:3]
        self.material = material
        self.tint = tint
        # How hard this box darkens its own edges. Full strength outlines the box, which is
        # right for a book board and wrong for one of three arms making up a sphere: there,
        # every interior seam gets drawn and the ball reads as a knobbly plus. Assemblies that
        # are meant to look like one solid turn it down.
        self.ao = float(ao)
        # The face that shows the item's own cover art (a book's front board), or None. The art
        # itself is attached at build time, from the item's 16x16 icon -- see cover_art().
        self.cover = cover
        self.decal = None
        self.rot = None
        if rot:
            self.set_rotation(*rot)

    def set_rotation(self, axis, angle, origin):
        # Minecraft rejects anything else outright, and a model that fails to load is a
        # purple-and-black cube with no error the player can see.
        if axis not in ("x", "y", "z"):
            raise SystemExit(f"rotation axis must be x, y or z, got {axis!r}")
        if float(angle) not in ROTATION_ANGLES:
            raise SystemExit(f"rotation angle must be one of {ROTATION_ANGLES}, got {angle!r}")
        self.rot = (axis, float(angle), [float(v) for v in origin])

    def size_texels(self):
        """Footprint in texels, clamped to at least 1 so a paper-thin box still has a face."""
        return [max(1, int(math.ceil((self.to[a] - self.frm[a]) * DETAIL))) for a in range(3)]


def tilt(boxes, axis, angle, origin=(8, 8, 8)):
    """Lean a whole assembly. Every box turns about the same origin, so it stays assembled."""
    for box in boxes:
        box.set_rotation(axis, angle, origin)
    return boxes


def net_size(box):
    w, h, d = box.size_texels()
    return 2 * d + 2 * w, d + h


def pack(boxes, width, gap=1):
    """Shelf-pack each box's UV net. Same approach as beast_skins, at item scale."""
    placements = {}
    x = y = gap
    shelf = 0
    for index, box in sorted(enumerate(boxes), key=lambda pair: -net_size(pair[1])[1]):
        nw, nh = net_size(box)
        if nw + 2 * gap > width:
            return None, width + 1          # this box cannot fit this sheet at any offset
        if x + nw + gap > width:
            x = gap
            y += shelf + gap
            shelf = 0
        placements[index] = (x, y)
        x += nw + gap
        shelf = max(shelf, nh)
    return placements, y + shelf + gap


def fit_atlas(boxes):
    """Smallest square sheet the whole item packs into."""
    for size in ATLAS_SIZES:
        placements, height = pack(boxes, size)
        if placements is not None and height <= size:
            return size, placements
    raise SystemExit("item does not pack into a 256px sheet; give it fewer or smaller boxes")


def face_rects(u, v, w, h, d):
    """Standard box-UV unwrap, in texels."""
    return {
        "up": (u + d, v, w, d),
        "down": (u + d + w, v, w, d),
        "east": (u, v + d, d, h),
        "north": (u + d, v + d, w, h),
        "west": (u + d + w, v + d, d, h),
        "south": (u + d + w + d, v + d, w, h),
    }


def texel_height(box, face, j):
    """Model-space Y of a texel, so the light can be about the object and not about the box.

    A face's net runs top-down, so row 0 is the top of a side face; the caps are flat.
    """
    if face == "up":
        return box.to[1]
    if face == "down":
        return box.frm[1]
    return box.to[1] - (j + 0.5) / DETAIL


def paint(img, box, rect, face, seed, span):
    """Paint one face's net: material, then the light. Cover art goes on after posterising."""
    x0, y0, fw, fh = rect
    px = img.load()
    _paint_material(px, box, rect, face, seed, span)


def _paint_decal(px, box, rect, face):
    """The icon's cover, at a whole-number scale and centred, lit like the face it sits on.

    Whole numbers only: a 1.8x nearest-neighbour stretch doubles every other icon pixel and the
    art turns lumpy. Whatever the integer fit leaves over keeps the board's own leather, which
    reads as the cover's margin.
    """
    x0, y0, fw, fh = rect
    art = box.decal
    k = max(1, min(fw // art.width, fh // art.height))
    art = art.resize((art.width * k, art.height * k), Image.NEAREST)
    ox, oy = x0 + (fw - art.width) // 2, y0 + (fh - art.height) // 2
    apx = art.load()
    shade = FACE_SHADE[face]
    for j in range(art.height):
        for i in range(art.width):
            r, g, b, a = apx[i, j]
            if a < 128 or not (x0 <= ox + i < x0 + fw and y0 <= oy + j < y0 + fh):
                continue
            px[ox + i, oy + j] = lit((r, g, b), shade)


def _paint_material(px, box, rect, face, seed, span):
    x0, y0, fw, fh = rect
    surface = MATERIALS[box.material]
    low, high = span
    for j in range(fh):
        for i in range(fw):
            f, overlay = surface(i, j, fw, fh, face, seed, noise(seed, i, j))
            f *= FACE_SHADE[face]
            # One light for the whole item, keyed to where the texel actually sits in model
            # space. Per-face shading alone lights every box as its own object, so a stack of
            # four boxes came out as four separately-lit slabs — which is most of why a hat
            # read as a ziggurat and a sphere read as a cluster.
            f *= 0.88 + 0.24 * (texel_height(box, face, j) - low) / max(0.001, high - low)
            # Contact shading. One ring at full strength alone left every face looking like
            # a sticker; a second, softer ring gives the cuboid a rounded edge instead.
            edge = min(i, j, fw - 1 - i, fh - 1 - j)
            if edge == 0:
                f *= 1.0 - 0.14 * box.ao
            elif edge == 1 and fw > 5 and fh > 5:
                f *= 1.0 - 0.06 * box.ao
            col = lit(box.colour, f)
            if overlay:
                col = mix(col + (255,), overlay[0] + (255,), overlay[1])[:3]
            px[x0 + i, y0 + j] = (col[0], col[1], col[2], 255)


def cover_art(item_id):
    """The cover region of the item's own icon: its opaque box, minus the page edge.

    Book icons are drawn cover-on with the fore-edge of the pages as a pale strip down the right;
    those columns are the page block, which the 3D book models as geometry, so they are cut off
    here. Columns are dropped from the right while they are mostly light.
    """
    path = os.path.join(ITEM_TEX_DIR, item_id + ".png")
    if not os.path.exists(path):
        return None
    icon = Image.open(path).convert("RGBA")
    bbox = icon.getbbox()
    if not bbox:
        return None
    icon = icon.crop(bbox)
    px = icon.load()

    def light(col):
        cells = [px[col, y] for y in range(icon.height) if px[col, y][3] >= 128]
        pale = [c for c in cells if 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2] > 150]
        return bool(cells) and len(pale) * 2 >= len(cells)

    right = icon.width
    while right > icon.width // 2 and (light(right - 1) or light(right - 2)):
        right -= 1
    return icon.crop((0, 0, right, icon.height))


def build(item_id, boxes, hold):
    art = None
    for box in boxes:
        if box.cover:
            art = art or cover_art(item_id)
            box.decal = art
    atlas, placements = fit_atlas(boxes)
    uv_scale = 16.0 / atlas
    img = Image.new("RGBA", (atlas, atlas), (0, 0, 0, 0))

    span = (min(b.frm[1] for b in boxes), max(b.to[1] for b in boxes))
    elements = []
    covers = []
    for index, box in enumerate(boxes):
        w, h, d = box.size_texels()
        u, v = placements[index]
        faces = {}
        for face, rect in face_rects(u, v, w, h, d).items():
            paint(img, box, rect, face, index * 31 + len(item_id), span)
            if box.decal is not None and face == box.cover:
                covers.append((box, rect, face))
            x0, y0, fw, fh = rect
            faces[face] = {"uv": [round(x0 * uv_scale, 4), round(y0 * uv_scale, 4),
                                  round((x0 + fw) * uv_scale, 4),
                                  round((y0 + fh) * uv_scale, 4)],
                           "texture": "#0"}
            if box.tint:
                faces[face]["tintindex"] = 0
        element = {"from": [round(v, 2) for v in box.frm],
                   "to": [round(v, 2) for v in box.to],
                   "faces": faces}
        if box.rot:
            axis, angle, origin = box.rot
            element["rotation"] = {"origin": [round(o, 2) for o in origin],
                                   "axis": axis, "angle": angle}
        elements.append(element)

    model = {
        "credit": CREDIT,
        "gui_light": "side",
        "textures": {"0": f"wizards_and_beasts:item/{item_id}_3d",
                     "particle": f"wizards_and_beasts:item/{item_id}_3d"},
        "elements": elements,
        "display": item_display.display_for(hold, item_display.cuboid_bounds(elements)),
    }
    # Enough palette entries for every material on every box to keep its own tones, but
    # still few enough that the sheet reads as Minecraft art rather than as a render.
    img = posterise(img, min(30, 8 + 3 * len({b.colour for b in boxes}) + len(boxes)))
    # Cover art last: it is already pixel art with its own small palette, and median-cut weights
    # colours by how many pixels carry them -- a gilt emblem of a dozen pixels on a board of
    # leather got folded into the leather and came out grey.
    px = img.load()
    for box, rect, face in covers:
        _paint_decal(px, box, rect, face)
    return img, model


def model_is_ours(path):
    """Safe to overwrite: absent, previously ours, or a bare item/generated stub.

    A stub is a model with nothing in it but a parent and a layer0 — replacing one with a
    real cuboid model is the entire point of this tool. Anything else was authored by
    hand and is left alone.
    """
    if not os.path.exists(path):
        return True
    try:
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError):
        return False
    if doc.get("credit") == CREDIT:
        return True
    # Comment keys are not content: several stubs carry a "PLACEHOLDER texture" note, and
    # refusing to touch those would leave exactly the models this tool exists to replace.
    keys = {k for k in doc if not k.startswith("_") and k != "credit"}
    return (doc.get("parent") == "minecraft:item/generated"
            and keys <= {"parent", "textures"}
            and set(doc.get("textures", {})) <= {"layer0"})


# --------------------------------------------------------------------------- shapes
#
# Each builder returns a list of boxes in model space, 0..16 on every axis. They are
# deliberately blunt: four or five cuboids is all a prop this size can carry before the
# silhouette stops reading, and every extra box costs atlas.

