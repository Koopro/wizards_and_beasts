def redisplay(only):
    """Recompute the display block of every model this tool wrote, and nothing else.

    Transforms are the part of these models that is tuned by looking at them in game; the
    geometry and the painted sheets are not. Keeping the two rewrites apart means a transform
    change never repaints a texture, and the diff shows exactly what moved.
    """
    changed = 0
    for item_id, boxes in sorted(ITEMS.items()):
        if (only and item_id not in only) or item_id in FLAT_ITEMS or is_geo(item_id):
            continue
        path = os.path.join(ITEM_MODEL_DIR, item_id + ".json")
        if not os.path.exists(path):
            continue
        model = item_display.load_json(path)
        if model.get("credit") != CREDIT:
            continue
        display = item_display.display_for(hold_of(boxes), item_display.cuboid_bounds(model["elements"]))
        if display != model.get("display"):
            model["display"] = display
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                json.dump(model, fh, indent=2)
                fh.write("\n")
            changed += 1
    print(f"display rewritten on {changed} models")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true",
                    help="overwrite even hand-authored models and textures")
    ap.add_argument("--only", default="", help="comma-separated item ids")
    ap.add_argument("--list", action="store_true", help="print the catalogue and stop")
    ap.add_argument("--display-only", action="store_true",
                    help="rewrite only the display block of models this tool owns; "
                         "geometry and sheets are left byte-for-byte alone")
    args = ap.parse_args()
    only = {s.strip() for s in args.only.split(",") if s.strip()}

    if args.list:
        for item_id in sorted(ITEMS):
            print(f"{item_id:44s} {len(ITEMS[item_id])} boxes")
        print(f"\n{len(ITEMS)} items")
        return 0

    if args.display_only:
        return redisplay(only)

    unknown = only - set(ITEMS)
    if unknown:
        raise SystemExit(f"not in the catalogue: {', '.join(sorted(unknown))}")

    written, skipped, flat, geo = [], [], [], []
    for item_id, boxes in sorted(ITEMS.items()):
        if only and item_id not in only:
            continue
        if item_id in FLAT_ITEMS:
            flat.append(item_id)
            continue
        if is_geo(item_id):
            geo.append(item_id)
            continue
        validate(item_id, boxes)
        tex_path = os.path.join(ITEM_TEX_DIR, item_id + "_3d.png")
        model_path = os.path.join(ITEM_MODEL_DIR, item_id + ".json")
        # Guard the *model*, not just the texture. Checking only the texture meant a model
        # that did not exist yet counted as regenerable and the existing JSON was
        # overwritten sight unseen — which is how ten item models got clobbered on the
        # first run. They happened to be trivial item/generated stubs; the next one might
        # not be.
        if not args.force and not (is_regenerable(tex_path, MARKER) and model_is_ours(model_path)):
            skipped.append(item_id)
            continue
        img, model = build(item_id, boxes, hold_of(boxes))
        save(img, tex_path, MARKER)
        os.makedirs(ITEM_MODEL_DIR, exist_ok=True)
        with open(model_path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(model, fh, indent=2)
            fh.write("\n")
        written.append(item_id)

    print(f"built {len(written)} 3D item models")
    if flat:
        print(f"left flat on purpose ({len(flat)}): {', '.join(flat)}")
    if geo:
        print(f"drawn by GeckoLib instead ({len(geo)}): {', '.join(geo)}")
    if skipped:
        print(f"skipped {len(skipped)} hand-authored: {', '.join(skipped)}")

    undeclared, stale = check_datagen_seam(written)
    if undeclared:
        print("\nModModelProvider.HAND_MODELLED_CANON is missing these, so datagen will keep\n"
              "emitting a flat stub for them into src/generated/resources:")
        for item_id in undeclared:
            print(f'        "{item_id}",')
        return 1
    if stale:
        print("\nHAND_MODELLED_CANON names ids this tool does not model; they will render as\n"
              "the missing-model cube: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
