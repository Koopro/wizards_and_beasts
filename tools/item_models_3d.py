def book(cover, pages="#e0d8c2", clasp=None, w=10, h=13, thick=1.5):
    """A closed book: two boards overhanging an inset page block, a spine that stands proud of
    them with two raised bands, and the title's own cover art on the front board.

    The first cut was boards flush with the pages and one leather colour on every face, which in
    the hand read as a coloured brick with a cream lid. What makes a book read at this size is the
    shadow line where the boards overhang the pages, the pale fore-edge between them, the ridged
    spine, and the cover -- which already exists, drawn, in the item's icon (see cover_art).

    Width and height still carry the identity as much as colour does: eleven books that differ
    only in hue are not eleven books.
    """
    x0, x1 = (16 - w) / 2, (16 + w) / 2
    y0, y1 = (16 - h) / 2, (16 + h) / 2
    depth = max(4.5, min(7.0, w * 0.55))
    z0, z1 = 8 - depth / 2, 8 + depth / 2
    boards = [
        Box([x0 + 0.5, y0, z0], [x1, y1, z0 + thick], cover, "leather"),
        Box([x0 + 0.5, y0, z1 - thick], [x1, y1, z1], cover, "leather", cover="south"),
    ]
    spine = Box([x0 - 0.25, y0 + 0.25, z0 + 0.25], [x0 + 1.25, y1 - 0.25, z1 - 0.25], cover, "leather")
    bands = [Box([x0 - 0.5, y, z0 + 0.5], [x0 + 0.5, y + 0.75, z1 - 0.5], cover, "leather", ao=0.6)
             for y in (y0 + h * 0.28, y1 - h * 0.28 - 0.75)]
    # Inset on the fore edge, head and tail, so the boards overhang it on three sides.
    block = Box([x0 + 1.25, y0 + 0.5, z0 + thick], [x1 - 0.5, y1 - 0.5, z1 - thick], pages, "paper")
    boxes = boards + [spine] + bands + [block]
    if clasp:
        boxes.append(Box([x1 - 1.5, 7, z0 - 0.3], [x1 + 0.5, 9, z1 + 0.3], clasp, "gold"))
    return boxes


