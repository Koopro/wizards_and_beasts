# blades. It fails for round: a Quaffle becomes a red cube, a Bludger a black cube, a
# Remembrall a grey box with a red smear. Rendered side by side against the sprites they
# were built from, the sprite won on every one of these, and the sprites were sitting
# unused on disk the whole time because the model bound `<id>_3d.png` instead.
#
# They are listed rather than deleted from ITEMS so the reason survives: without this note
# the obvious "fix" is to model the missing ones, which is how they got cubed in the first
# place. `model_is_ours` treats a bare item/generated stub as overwritable — that is the
# whole point of this tool — so a flat model alone would not have survived the next run.
# Membership here is what protects it.
