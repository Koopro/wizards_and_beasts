def ball(colour, r=5, material="solid"):
    """A cube with six caps: the low-poly sphere.

    Three crossing bars alone leave a deep notch at all eight corners, so the thing reads as a
    knobbly plus however thin the arms get. A centre cube slightly wider than the arms fills
    those notches, and the arms become caps poking out of it — the same silhouette a chamfered
    sphere has. `ao` stays low so the seams between the four boxes are not drawn.
    """
    a, b = 8 - r, 8 + r
    inset = max(1.0, r * 0.62)
    c, d = 8 - r + inset, 8 + r - inset
    core = r * 0.78
    return [
        Box([8 - core, 8 - core, 8 - core], [8 + core, 8 + core, 8 + core],
            colour, material, ao=0.25),
        Box([a, c, c], [b, d, d], colour, material, ao=0.25),
        Box([c, a, c], [d, b, d], colour, material, ao=0.25),
        Box([c, c, a], [d, d, b], colour, material, ao=0.25),
    ]


