# --------------------------------------------------------------------------- validation

def validate(item_id, boxes):
    """Catch the mistakes that produce a model which loads but shows nothing useful.

    A box outside the model bounds makes Minecraft reject the whole file, and a box wholly
    inside another is invisible geometry that still costs atlas — both are easy to write and
    impossible to see in the JSON.
    """
    problems = []
    for index, box in enumerate(boxes):
        for axis, name in enumerate("xyz"):
            lo, hi = box.frm[axis], box.to[axis]
            if hi <= lo:
                problems.append(f"box {index} has {name} from {lo} to {hi}")
            if lo < -16 or hi > 32:
                problems.append(f"box {index} {name} {lo}..{hi} is outside the -16..32 bounds")
    for a, box in enumerate(boxes):
        for b, other in enumerate(boxes):
            if a == b or box.rot != other.rot:
                continue
            if all(other.frm[k] <= box.frm[k] and box.to[k] <= other.to[k] for k in range(3)):
                problems.append(f"box {a} is entirely inside box {b} and will never be seen")
    if problems:
        raise SystemExit(f"{item_id}: " + "; ".join(problems))


