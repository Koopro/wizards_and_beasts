def gem(colour):
    """Three boxes turned 45 degrees on Y, stepping in to a table.

    Two things were making a cut stone look like rubble. Five steps is too many — each one is
    another ledge, and the stack turns into a pinecone. And a box shows the viewer a *corner*
    at the GUI angle, which is the least gem-like thing it can do; turning every box 45
    degrees presents flat faces instead, so the silhouette is a diamond and the facets have
    somewhere to sit.
    """
    pivot = [8, 8, 8]
    return [
        Box([5.5, 2.5, 5.5], [10.5, 7, 10.5], colour, "gem", ao=0.3, rot=("y", 45, pivot)),
        Box([4.5, 7, 4.5], [11.5, 9.5, 11.5], colour, "gem", ao=0.3, rot=("y", 45, pivot)),
        Box([6, 9.5, 6], [10, 12.5, 10], colour, "gem", ao=0.3, rot=("y", 45, pivot)),
    ]


def ring(metal, stone):
    """A thick band under a stone, turned so you can see through it.

    A ring is only legible when the hole is. The GUI transform already turns the model 225
    degrees, which leaves an axis-aligned band at 45 degrees to the camera — half a hole.
    Turning it a further -45 brings the face square on; +45 takes it to 90 and the ring
    disappears into a sliver, which is the sign error worth remembering here.
    """
    pivot = [8, 8, 8]
    return [
        Box([4.5, 2.5, 6.5], [11.5, 4.5, 9.5], metal, "gold", rot=("y", -45, pivot)),
        Box([4.5, 9.5, 6.5], [11.5, 11.5, 9.5], metal, "gold", rot=("y", -45, pivot)),
        Box([4.5, 4.5, 6.5], [6.5, 9.5, 9.5], metal, "gold", rot=("y", -45, pivot)),
        Box([9.5, 4.5, 6.5], [11.5, 9.5, 9.5], metal, "gold", rot=("y", -45, pivot)),
        Box([5.5, 11, 5.8], [10.5, 14.5, 10.2], stone, "gem", ao=0.4, rot=("y", -45, pivot)),
    ]


