def hat(cloth, band=None, brim=13, peak=15.5):
    """Brim, crown, and a point flopped right over at 45 degrees.

    Every concentric step is a horizontal ledge, and the eye reads a run of ledges as stairs
    — so the cure is not smaller steps but *fewer* of them. Three boxes: the brim, one tall
    crown, and a point thrown far enough off-axis that the outline is a hook rather than a
    staircase. Leaning only the tip while the crown still stepped twice fixed nothing.
    """
    x0 = (16 - brim) / 2
    boxes = [
        Box([x0, 1, x0], [16 - x0, 2.5, 16 - x0], cloth, "cloth"),
        Box([5, 2.5, 5], [11, 10, 11], cloth, "cloth", ao=0.5),
        Box([6.2, 9, 6.2], [9.8, peak, 9.8], cloth, "cloth", ao=0.5,
            rot=("z", 45, [8, 9.5, 8])),
    ]
    if band:
        boxes.append(Box([4.8, 2.6, 4.8], [11.2, 4.4, 11.2], band, "cloth"))
    return boxes


