DEFAULT_HOLD = "object"


class Held(list):
    """A builder's box list, carrying the hold class of the builder that made it."""
    hold = DEFAULT_HOLD


def _held_by(builder, hold):
    def build_held(*args, **kwargs):
        boxes = Held(builder(*args, **kwargs))
        boxes.hold = hold
        return boxes
    build_held.__name__ = builder.__name__
    build_held.__doc__ = builder.__doc__
    return build_held


for _hold, _names in HOLD_BY_BUILDER.items():
    for _name in _names:
        globals()[_name] = _held_by(globals()[_name], _hold)


def hold_of(boxes):
    return getattr(boxes, "hold", DEFAULT_HOLD)


