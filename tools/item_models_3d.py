GEO_DIR = os.path.join(ASSETS, "geckolib", "models", "item")


def is_geo(item_id):
    """An AnimatedItem draws its GeckoLib model in hand (tools/item_geo.py); a cuboid here would
    never be seen, and its only job -- a display block -- is now the geo's own `<id>_held`."""
    return os.path.exists(os.path.join(GEO_DIR, item_id + ".geo.json"))


def check_datagen_seam(written):
    """Report canon stubs that this tool models but ModModelProvider still flat-generates."""
    canon = read_ids(CANON_REGISTRY, CANON_ID)
    if canon is None:
        return []
    declared = set()
    if os.path.exists(MODEL_PROVIDER):
        with open(MODEL_PROVIDER, encoding="utf-8") as fh:
            block = DECLARED_BLOCK.search(fh.read())
        if block:
            declared = set(re.findall(r'"([a-z0-9_]+)"', block.group(1)))
    modelled_canon = {i for i in ITEMS if i in canon and i not in FLAT_ITEMS and not is_geo(i)}
    return sorted(modelled_canon - declared), sorted(declared - modelled_canon)


